function isoDay(monthDate: Date, day: number): string {
  const start = startOfMonth(monthDate);
  const clampedDay = Math.min(Math.max(day, 1), 28);
  return format(addDays(start, clampedDay - 1), 'yyyy-MM-dd');
}

